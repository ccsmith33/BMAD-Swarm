import { existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { getProjectPaths } from '../utils/paths.js';
import { loadSwarmConfig, getAgentNames } from '../utils/config.js';
import { readFileSafe } from '../utils/fs-helpers.js';
import { METHODOLOGY_SHIP_LIST } from '../utils/scaffold-paths.js';

export function registerDoctorCommand(program) {
  program
    .command('doctor')
    .description('Check project configuration health and report issues')
    .addHelpText('after', `
Examples:
  $ bmad-swarm doctor    Run all health checks
`)
    .action(async () => {
      try {
        await runDoctor();
      } catch (err) {
        console.error(`Error: ${err.message}`);
        process.exit(1);
      }
    });
}

async function runDoctor() {
  const projectRoot = process.cwd();
  const paths = getProjectPaths(projectRoot);
  let hasIssues = false;

  console.log('\nBMAD Swarm Health Check\n');

  // 1. swarm.yaml
  if (existsSync(paths.swarmYaml)) {
    try {
      const config = loadSwarmConfig(paths.swarmYaml);
      check(true, 'swarm.yaml exists and is valid');

      // 3. Agent files
      const enabledAgents = getAgentNames().filter(name => {
        const agentConfig = config.agents?.[name];
        return agentConfig?.enabled !== false;
      });
      let agentIssues = 0;
      for (const name of enabledAgents) {
        const agentPath = join(paths.agentsDir, `${name}.md`);
        if (!existsSync(agentPath)) {
          agentIssues++;
        }
      }
      if (agentIssues === 0) {
        check(true, `.claude/agents/ has all ${enabledAgents.length} enabled agents`);
      } else {
        check(false, `.claude/agents/ is missing ${agentIssues} agent file(s)`, 'Run `bmad-swarm update` to regenerate');
        hasIssues = true;
      }
    } catch (err) {
      check(false, `swarm.yaml has validation errors: ${err.message}`, 'Fix the errors in swarm.yaml');
      hasIssues = true;
    }
  } else {
    check(false, 'swarm.yaml not found', 'Run `bmad-swarm init` to create');
    hasIssues = true;
  }

  // 4. CLAUDE.md
  if (existsSync(paths.claudeMd)) {
    const content = readFileSafe(paths.claudeMd);
    if (content && /<!-- bmad-generated:[a-f0-9]+/.test(content)) {
      check(true, 'CLAUDE.md exists and was generated by bmad-swarm');
    } else {
      check(false, 'CLAUDE.md exists but may not be generated by bmad-swarm', 'Run `bmad-swarm update` to regenerate');
      hasIssues = true;
    }
  } else {
    check(false, 'CLAUDE.md not found', 'Run `bmad-swarm update` to generate');
    hasIssues = true;
  }

  // 5. Hooks
  if (existsSync(paths.hooksDir)) {
    const hooks = readdirSync(paths.hooksDir).filter(f => f.endsWith('.js') || f.endsWith('.cjs') || f.endsWith('.sh'));
    if (hooks.length > 0) {
      check(true, `.claude/hooks/ has ${hooks.length} hook(s)`);
    } else {
      check(false, '.claude/hooks/ exists but has no hooks', 'Run `bmad-swarm update` to regenerate');
      hasIssues = true;
    }
  } else {
    check(false, '.claude/hooks/ not found', 'Run `bmad-swarm update` to generate');
    hasIssues = true;
  }

  // 6. settings.json
  if (existsSync(paths.settingsJson)) {
    check(true, '.claude/settings.json exists');
  } else {
    check(false, '.claude/settings.json not found', 'Run `bmad-swarm update` to generate');
    hasIssues = true;
  }

  // 6.5. Slash commands
  const commandsDir = join(paths.claudeDir, 'commands');
  if (existsSync(commandsDir)) {
    const commandFiles = readdirSync(commandsDir).filter(f => f.endsWith('.md'));
    const identityCount = commandFiles.filter(f => f.startsWith('identity-')).length;
    const workflowCount = commandFiles.length - identityCount;
    if (identityCount > 0 && workflowCount > 0) {
      check(true, `.claude/commands/ has ${identityCount} identity + ${workflowCount} workflow commands`);
    } else {
      check(false, `.claude/commands/ is missing identity or workflow commands`, 'Run `bmad-swarm update` to regenerate');
      hasIssues = true;
    }
  } else {
    check(false, '.claude/commands/ not found', 'Run `bmad-swarm update` to generate');
    hasIssues = true;
  }

  // 6.6. Shipped methodology subset (self-containment, CB-1)
  if (existsSync(paths.bmadMethodologyDir)) {
    const shipped = METHODOLOGY_SHIP_LIST.filter((rel) => existsSync(join(paths.bmadMethodologyDir, rel)));
    if (shipped.length === METHODOLOGY_SHIP_LIST.length) {
      check(true, `.claude/bmad/methodology/ has all ${METHODOLOGY_SHIP_LIST.length} shipped files`);
    } else {
      check(false, `.claude/bmad/methodology/ is missing ${METHODOLOGY_SHIP_LIST.length - shipped.length} shipped file(s)`, 'Run `bmad-swarm update` to regenerate');
      hasIssues = true;
    }
  } else {
    check(false, '.claude/bmad/methodology/ not found', 'Run `bmad-swarm update` to ship the methodology subset');
    hasIssues = true;
  }

  // 6.7. Skew note (advisory): generated agents/commands that were manually
  // modified may retain dangling repo-relative refs (`methodology/…`,
  // `agents/<role>.md`) that only resolved in the dev repo. Report, don't fail
  // — user-modified files are their owner's responsibility (§3.4).
  reportPathSkew(paths);

  // 7. project.yaml
  if (existsSync(paths.projectYaml)) {
    check(true, 'project.yaml exists');
  } else {
    check(false, 'project.yaml not found', 'Run `bmad-swarm init` to create');
    hasIssues = true;
  }

  // 8. Artifact directories
  const artifactDirs = ['exploration', 'planning', 'design', 'implementation', 'reviews', 'context'];
  let missingDirs = 0;
  for (const dir of artifactDirs) {
    if (!existsSync(join(paths.artifactsDir, dir))) {
      missingDirs++;
    }
  }
  if (missingDirs === 0) {
    check(true, 'All artifact directories exist');
  } else {
    check(false, `Missing ${missingDirs} artifact director${missingDirs > 1 ? 'ies' : 'y'}`, 'Run `bmad-swarm init` to create');
    hasIssues = true;
  }

  // 9. Orphaned overrides
  if (existsSync(paths.overridesAgentsDir)) {
    const overrides = readdirSync(paths.overridesAgentsDir).filter(f => f.endsWith('.md'));
    const orphaned = overrides.filter(f => !getAgentNames().includes(f.replace('.md', '')));
    if (orphaned.length === 0) {
      check(true, 'No orphaned override files');
    } else {
      check(false, `Orphaned override files: ${orphaned.join(', ')}`, 'Remove unused override files from overrides/agents/');
      hasIssues = true;
    }
  }

  console.log('');
  if (hasIssues) {
    console.log('Issues found. See suggestions above.');
    process.exit(1);
  } else {
    console.log('All checks passed!');
  }
}

function check(pass, message, fix) {
  const icon = pass ? '\u2713' : '\u2717';
  console.log(`  ${icon} ${message}`);
  if (!pass && fix) {
    console.log(`    Fix: ${fix}`);
  }
}

// A dangling repo-relative reference: `methodology/\u2026` not already shipped-prefixed,
// or `agents/<role>.md` not already under `.claude/`.
function danglingRefRegex() {
  const roles = getAgentNames().map((r) => r.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|');
  return new RegExp(`(?<![\\w/.])(methodology/|agents/(?:${roles})\\.md)`);
}

/**
 * Advisory scan: report generated agent/command files whose bodies still carry
 * dangling repo-relative references. These appear only when a user manually
 * edited a generated file and reintroduced (or kept) an un-rewritten path.
 * @param {object} paths - Project paths
 */
function reportPathSkew(paths) {
  const re = danglingRefRegex();
  const dirs = [paths.agentsDir, join(paths.claudeDir, 'commands')];
  const flagged = [];
  for (const dir of dirs) {
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).filter((n) => n.endsWith('.md'))) {
      const content = readFileSafe(join(dir, f));
      if (content && re.test(content)) {
        flagged.push(join(dir.endsWith('commands') ? 'commands' : 'agents', f));
      }
    }
  }
  if (flagged.length > 0) {
    console.log(`  \u2139 Path skew: dangling repo-relative refs in ${flagged.length} generated file(s): ${flagged.join(', ')}`);
    console.log('    These reference `methodology/` or `agents/<role>.md` instead of the shipped');
    console.log('    `.claude/bmad/methodology/` / `.claude/agents/` paths. Likely manually edited.');
    console.log('    Fix: re-run `bmad-swarm update --force`, or update the refs by hand.');
  }
}

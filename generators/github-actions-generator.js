import { join } from 'node:path';
import { writeFileSafe } from '../utils/fs-helpers.js';

/**
 * Generate GitHub Actions workflow for bmad-swarm validation.
 *
 * The trigger paths (artifacts/**, swarm.yaml) assume the D-042 sharing
 * model: those files are git-tracked, so PRs can touch them and fire the
 * workflow (F-018). The workflow deliberately runs only `bmad-swarm
 * validate` — `doctor` needs .claude/, which stays gitignored and is absent
 * from CI checkouts.
 *
 * F-023: the validate step runs `npx --yes bmad-swarm@latest validate`
 * rather than `npm install -g bmad-swarm@<local version>`. Pinning the
 * repo-local package.json version guaranteed a 404 (and a red first run)
 * for every generated project until that exact version reached npm; the
 * `@latest` spec resolves whatever is actually published. The workflow is
 * only *honest* once bmad-swarm is on npm — the CHANGELOG calls this out.
 * A human may swap `@latest` for a specific about-to-publish version at the
 * publish sign-off (design §5, default `@latest`).
 *
 * @param {string} projectRoot - Project root directory
 * @returns {string} Path to generated workflow file
 */
export function generateGitHubWorkflow(projectRoot) {
  const workflowDir = join(projectRoot, '.github', 'workflows');
  const workflowPath = join(workflowDir, 'bmad-validate.yml');

  const content = `# BMAD Swarm - Artifact Validation Workflow
# Generated by bmad-swarm init --github
# Runs artifact validation on pushes to main and on pull requests to catch
# quality issues early.
#
# Requires artifacts/ and swarm.yaml to be git-tracked (D-042 sharing
# model) — a gitignored path can never match the trigger filter below.

name: BMAD Validate

on:
  push:
    branches: [main, master]
    paths:
      - 'artifacts/**'
      - 'swarm.yaml'
  pull_request:
    branches: [main, master]
    paths:
      - 'artifacts/**'
      - 'swarm.yaml'

permissions:
  contents: read

jobs:
  validate:
    name: Validate Artifacts
    runs-on: ubuntu-latest

    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '22'

      - name: Validate artifacts
        run: npx --yes bmad-swarm@latest validate
`;

  writeFileSafe(workflowPath, content);
  return workflowPath;
}
